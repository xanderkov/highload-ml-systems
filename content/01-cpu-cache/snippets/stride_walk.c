/* Обход по цепочке: следующий индекс лежит в текущем элементе.

   Так измеряется именно задержка памяти. Процессор не может начать
   следующее чтение, пока не пришёл результат предыдущего, — адрес ещё не
   известен. Ни префетчер, ни внеочередное исполнение здесь не помогают,
   поэтому время одного шага и есть время похода в память. */
double walk(const long *next, int n, long steps) {
    (void)n;
    long idx = 0;
    for (long s = 0; s < steps; s++) idx = next[idx];
    return (double)idx;
}
