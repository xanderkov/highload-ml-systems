#include <stdlib.h>

/* Перемножаем две матрицы n x n и возвращаем контрольную сумму результата.
   Обе матрицы лежат построчно: элемент (i, j) — по индексу i * n + j.

   Это наивные три вложенных цикла, ровно как в учебнике. Проблема в
   выделенной строке: матрица b обходится по столбцам, и ради одного элемента
   результата вы проходите её целиком — n раз подряд, для каждого из n * n
   элементов. Всё, что подтянулось в кэш на предыдущем шаге, к следующему
   использованию оттуда уже вытеснено.

   Найдите способ переиспользовать то, что уже лежит в кэше, до того как оно
   оттуда уйдёт. Перестановки одних только циклов здесь мало — подумайте о
   том, чтобы считать результат не целиком, а кусками, которые целиком
   помещаются в кэш первого уровня. Его размер вы измерили в начале раздела. */
double matmul(const double *a, const double *b, int n) {
    double *c = malloc((size_t)n * (size_t)n * sizeof(double));
    if (c == NULL) return 0.0;

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            double sum = 0.0;
            for (int k = 0; k < n; k++)
                sum += a[(size_t)i * n + k] * b[(size_t)k * n + j]; /* <-- шаг по b: n * 8 байт */
            c[(size_t)i * n + j] = sum;
        }
    }

    double total = 0.0;
    for (size_t t = 0; t < (size_t)n * (size_t)n; t++) total += c[t];
    free(c);
    return total;
}
