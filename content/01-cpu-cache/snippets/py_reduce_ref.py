def reduce_rows(a):
    """То же самое одной строкой: обход целиком уходит внутрь NumPy.

    a.max(axis=1) идёт по каждой строке подряд, по соседним адресам, без
    единого промежуточного объекта на элемент. Цикл никуда не делся — он
    просто выполняется скомпилированным кодом над непрерывным блоком памяти.
    """
    return float(a.max(axis=1).sum())
