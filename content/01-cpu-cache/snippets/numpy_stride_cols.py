def reduce_stride(a):
    """Складывает каждый восьмой столбец матрицы.

    Тех же самых чисел ровно столько же (матрица симметрична), и сложений
    ровно столько же. Но восемь double — это ровно одна кэш-линия в 64 байта,
    поэтому шаг 8 по столбцам означает: из каждой подтянутой линии берётся
    одно число, а семь остальных приезжают из памяти впустую.
    """
    return float(a[:, ::8].sum())
