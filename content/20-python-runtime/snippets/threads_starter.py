def config(cores: int) -> tuple[int, int]:
    """Сколько процессов запустить и сколько потоков torch дать каждому.

    cores — число логических CPU, доступных процессу. Возвращает
    (число процессов, аргумент torch.set_num_threads в каждом процессе).
    """
    # Как делают «по умолчанию»: 4 воркера, а torch в каждом берёт все CPU.
    return 4, cores
